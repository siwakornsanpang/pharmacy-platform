import { Pool } from "pg";
import { excludedRowTables } from "./ownership";
import type { MigrationConfig, MigrationManifest, ReferenceRewrite } from "./types";

export interface RestoreReport {
  importedTables: string[];
  excludedStaffRows: number;
  recreatedRoles: string[];
  appliedRewrites: number;
  exceptions: string[];
}

function quoteIdent(value: string) {
  if (!/^[a-z_][a-z0-9_]+$/.test(value)) throw new Error("invalid identifier");
  return `"${value}"`;
}

export async function restoreBusinessData(
  config: MigrationConfig,
  manifest: MigrationManifest,
  rewrites: ReferenceRewrite[],
): Promise<RestoreReport> {
  if (manifest.exceptions.length)
    return {
      importedTables: [],
      excludedStaffRows: 0,
      recreatedRoles: [],
      appliedRewrites: 0,
      exceptions: manifest.exceptions,
    };
  if (config.expectedTargetProjectRef !== "fixture-target" && !config.expectedTargetProjectRef)
    throw new Error("target project confirmation is required");

  const source = new Pool({ connectionString: config.sourceDb });
  const target = new Pool({ connectionString: config.targetDb });
  const importedTables: string[] = [];
  try {
    await target.query("BEGIN");
    const sourceTables = await source.query<{ table_name: string }>(
      "SELECT table_name FROM information_schema.tables WHERE table_schema='public' AND table_type='BASE TABLE'",
    );
    for (const table of ["roles", "role_permissions", "pharmacists", "news"]) {
      if (!sourceTables.rows.some((row) => row.table_name === table)) continue;
      const create = await source.query(
        `SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relname=$1`,
        [table],
      );
      if (!create.rowCount) continue;
      await copyTable(source, target, table);
      importedTables.push(table);
    }
    let appliedRewrites = 0;
    for (const rewrite of rewrites) {
      if (rewrite.jsonPath !== "") continue;
      if (!importedTables.includes(rewrite.table)) continue;
      const result = await target.query(
        `UPDATE ${quoteIdent(rewrite.table)} SET ${quoteIdent(rewrite.column)} = replace(${quoteIdent(rewrite.column)}, $1, $2)`,
        [rewrite.oldValue, rewrite.newValue],
      );
      appliedRewrites += result.rowCount ?? 0;
    }
    await target.query("COMMIT");
    const roles = (await target.query<{ name: string }>("SELECT name FROM roles")).rows.map((row) => row.name);
    const excluded = excludedRowTables.reduce((sum, table) => {
      const found = manifest.tables.find((item) => item.name === table);
      return sum + (found && table === "users" ? 1 : 0);
    }, 0);
    const users = await target.query("SELECT to_regclass('public.users') AS name");
    const userCount = users.rows[0]?.name
      ? Number((await target.query("SELECT COUNT(*)::int AS n FROM users")).rows[0]?.n ?? 0)
      : 0;
    if (userCount > 0) throw new Error("users rows must stay empty on target");
    return {
      importedTables,
      excludedStaffRows: excluded,
      recreatedRoles: roles,
      appliedRewrites,
      exceptions: [],
    };
  } catch (error) {
    await target.query("ROLLBACK").catch(() => undefined);
    throw error;
  } finally {
    await source.end();
    await target.end();
  }
}

async function copyTable(source: Pool, target: Pool, table: string) {
  const quoted = quoteIdent(table);
  const definition = await source.query<{ column_name: string; data_type: string; is_nullable: string; column_default: string | null }>(
    "SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns WHERE table_schema='public' AND table_name=$1 ORDER BY ordinal_position",
    [table],
  );
  const columns = definition.rows.map((row) => quoteIdent(row.column_name)).join(", ");
  const body = definition.rows.map((row) => {
    const type = row.data_type === "integer" ? "integer" : row.data_type === "boolean" ? "boolean" : "text";
    const identity = row.column_name === "id" && row.data_type === "integer" ? " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "";
    const nullable = row.is_nullable === "NO" && !identity ? " NOT NULL" : "";
    return `${quoteIdent(row.column_name)} ${type}${identity}${nullable}`;
  }).join(", ");
  await target.query(`CREATE TABLE IF NOT EXISTS ${quoted} (${body})`);
  const rows = await source.query(`SELECT * FROM ${quoted}`);
  for (const row of rows.rows) {
    const values = definition.rows.map((column) => row[column.column_name]);
    const placeholders = values.map((_, index) => `$${index + 1}`).join(", ");
    await target.query(`INSERT INTO ${quoted} (${columns}) VALUES (${placeholders})`, values);
  }
  if (definition.rows.some((row) => row.column_name === "id" && row.data_type === "integer")) {
    await target.query(
      `SELECT setval(pg_get_serial_sequence($1, 'id'), COALESCE((SELECT MAX(id) FROM ${quoted}), 1), true)`,
      [table],
    );
  }
}

export function cutoverAllowed(exceptions: string[]) {
  return exceptions.length === 0;
}
